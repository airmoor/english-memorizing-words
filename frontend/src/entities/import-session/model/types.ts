// ── ImportStatus ──────────────────────────────────────────────────────────────

/**
 * Overall outcome of an import execution.
 *
 * Sync MVP returns one of: completed | partial_failure | no_changes | failed.
 * 'queued' and 'processing' are reserved for a future async job mode where the
 * backend queues enrichment work and the client polls for status updates.
 *
 * Key distinction between no_changes and failed:
 *   no_changes — request succeeded; every word was already in vocabulary or was a
 *                within-batch duplicate. Nothing was imported, but nothing went wrong.
 *   failed     — request processed; errors prevented any word from being imported.
 */
export const IMPORT_STATUSES = [
  'queued',          // reserved: future async mode
  'processing',      // reserved: future async mode
  'completed',       // all submitted words successfully imported
  'partial_failure', // some imported, some failed enrichment
  'no_changes',      // succeeded — all rows were duplicates/skipped; nothing created
  'failed',          // nothing imported due to enrichment errors
] as const

export type ImportStatus = (typeof IMPORT_STATUSES)[number]

// ── ParsedRow — client-side representation ────────────────────────────────────

/**
 * All row statuses the frontend can assign or receive.
 * 'duplicate_vocabulary' is server-only — the parser never produces it directly,
 * but the frontend may receive it back from the preview endpoint.
 */
export const IMPORT_ROW_STATUSES = [
  'valid',
  'duplicate_vocabulary',    // server-only: word already in user's vocabulary
  'duplicate_within_batch',  // parser-owned: word appears earlier in this batch
  'error',
] as const

export type ImportRowStatus = (typeof IMPORT_ROW_STATUSES)[number]

/**
 * Subset of statuses the parser can assign — excludes server-only 'duplicate_vocabulary'.
 */
export const PARSER_ROW_STATUSES = [
  'valid',
  'duplicate_within_batch',
  'error',
] as const

export type ParserRowStatus = (typeof PARSER_ROW_STATUSES)[number]

/** A row produced by a parser — fully typed before server preview call. */
export interface ParsedRow {
  /**
   * Stable client-generated identifier for this row (UUID v4).
   * Generated by the parser at parse time via crypto.randomUUID().
   * Sent to the server in the execute payload and echoed back in error rows
   * so the frontend can highlight exactly which source rows failed.
   */
  clientRowId: string
  word: string
  lineNumber: number
  /**
   * Original raw text of the source line before normalisation.
   * Used only for display in the preview UI — not sent to the server.
   * Capped at 500 chars to bound memory for large CSV imports with long notes.
   */
  rawText: string
  status: ImportRowStatus
  reason?: string
  /** Row-level tags (from CSV column or Anki mapping) */
  tags?: string[]
  /** Row-level board name (from CSV column) */
  board?: string
  /** Row-level note (from CSV column) */
  notes?: string
}

// ── ImportSettings — client-side settings state ───────────────────────────────

export interface ImportSettings {
  boardId?: string
  tagIds?: string[]
  duplicateMode: 'skip' | 'import-anyway'
}

// ── API request/response shapes ───────────────────────────────────────────────

export interface ImportPreviewRow {
  word: string
  status: ImportRowStatus
  reason?: string
  /**
   * Echoed from the request payload — matches the ParsedRow.clientRowId that was sent.
   * Use this to correlate server preview results back to local ParsedRow[] without
   * relying on fragile array-index matching.
   */
  clientRowId?: string
  /**
   * Echoed 1-based source line number from the request payload.
   * Preserved as-is from the parser (accurate for CSV, Anki, multi-header files).
   */
  lineNumber?: number
}

export interface ImportPreviewResult {
  rows: ImportPreviewRow[]
}

export interface ImportErrorRow {
  word: string
  reason: string
  /** Echoed from request payload — identifies the exact source row that failed. */
  clientRowId?: string
  /** Echoed 1-based line number from request payload — for display in error list. */
  lineNumber?: number
}

export interface ImportExecuteResult {
  status: ImportStatus
  imported: number
  skipped: number
  /**
   * Within-batch duplicates removed before processing — first occurrence wins.
   * Included so the result summary can fully account for all submitted rows:
   *   submitted = imported + skipped + duplicatesIgnored + errors
   */
  duplicatesIgnored: number
  errors: number
  errorRows: ImportErrorRow[]
}

// ── ImportSession — persistent session record from the API ────────────────────

/** A failed-row snapshot stored inside an ImportSession. */
export interface ImportSessionErrorRow {
  word: string
  reason: string
  clientRowId?: string
  lineNumber?: number
}

/**
 * A persisted import session returned by GET /import/sessions or GET /import/sessions/:id.
 * Mirrors `ImportSessionDto` from the backend.
 */
export interface ImportSession {
  id: string
  sourceType: 'paste' | 'csv' | 'anki'
  status: 'completed' | 'partial_failure' | 'no_changes' | 'failed'
  submitted: number
  imported: number
  skipped: number
  duplicatesIgnored: number
  errors: number
  errorRows: ImportSessionErrorRow[]
  /**
   * Words successfully imported in this session (capped snapshot).
   * Empty array for sessions created before this field was added to the API.
   * Use `imported` for the accurate total; show "…and N more" when
   * `imported > importedWords.length`.
   */
  importedWords: string[]
  createdAt: string
}

export interface ImportSessionList {
  sessions: ImportSession[]
}

// ── ImportFlowError — typed error model ───────────────────────────────────────

/**
 * Typed error model for the import flow.
 * Replaces the untyped `string | null` so callers can distinguish error kinds
 * and show different recovery UI (e.g. retry vs. manual search).
 */
export type ImportFlowError = {
  /** Discriminator for the error category */
  type: 'network' | 'parse' | 'validation' | 'server'
  /** Human-readable message for display in the UI */
  message: string
  /**
   * Structured validation details — only present when type === 'validation'.
   * Mirrors ValidationErrorDetail from base.ts.
   * Used to: (a) mark affected preview rows as 'error', (b) render a smart
   * grouped summary in the error step instead of raw paths.
   */
  details?: Array<{ path: string; constraint: string; message: string }>
}
